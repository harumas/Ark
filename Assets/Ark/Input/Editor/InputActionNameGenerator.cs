using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;
using UnityEngine.InputSystem;

namespace Ark.Input.Editor
{
    /// <summary>
    /// InputActionのGuidを全て生成するクラス
    /// </summary>
    internal static class InputActionNameGenerator
    {
        private const string _NamespaceName = "Ark.Input";
        private const string _ClassName = "ActionGuid";
        private const string _MapIdFieldName = "MapId";
        private const string _ExportFolder = "Assets/Export";
        private const string _SavePath = _ExportFolder + "/" + _ClassName + ".cs";
        private const string _Indent = "    ";

        /// <summary>
        /// そのままでは識別子にできないC#の予約語
        /// </summary>
        private static readonly HashSet<string> _ReservedKeywords = new()
        {
            "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked",
            "class", "const", "continue", "decimal", "default", "delegate", "do", "double", "else", "enum",
            "event", "explicit", "extern", "false", "finally", "fixed", "float", "for", "foreach", "goto",
            "if", "implicit", "in", "int", "interface", "internal", "is", "lock", "long", "namespace",
            "new", "null", "object", "operator", "out", "override", "params", "private", "protected", "public",
            "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc", "static", "string",
            "struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked",
            "unsafe", "ushort", "using", "virtual", "void", "volatile", "while"
        };

        [MenuItem("InputSystem/GenerateActionName")]
        private static void Generate()
        {
            var actionAsset = InputSystem.actions;

            if (actionAsset == null)
            {
                Debug.LogError("Project-wide Input Actionsが設定されていません。" +
                               "Project Settings > Input System Package から設定してください。");
                return;
            }

            var code = BuildCode(actionAsset);

            if (WriteIfChanged(code) == false)
            {
                Debug.Log(_SavePath + " は最新のため更新しませんでした。");
                return;
            }

            Debug.Log(_SavePath + " にInputActionのGuidを生成しました。");
        }

        private static string BuildCode(InputActionAsset actionAsset)
        {
            // namespace直下でクラス名が衝突しないように採番する
            var typeNames = new HashSet<string> { _ClassName };
            var actionMaps = actionAsset.actionMaps
                .Select(actionMap => (actionMap, typeName: ResolveUniqueName(actionMap.name, typeNames)))
                .ToArray();

            var builder = new StringBuilder();

            builder.Append("// <auto-generated>\n")
                .Append($"// This code was generated by {nameof(InputActionNameGenerator)}.\n")
                .Append("// </auto-generated>\n\n")
                .Append("using System;\n\n")
                .Append($"namespace {_NamespaceName}\n")
                .Append("{\n");

            //ActionMapを集めるクラスの生成
            AppendActionMapHolder(builder, actionMaps);

            //ActionMapのGuidを集めるクラスの生成
            foreach (var (actionMap, typeName) in actionMaps)
            {
                builder.Append('\n');
                AppendActionMap(builder, actionMap, typeName);
            }

            builder.Append("}\n");

            return builder.ToString();
        }

        private static void AppendActionMapHolder(StringBuilder builder,
            (InputActionMap actionMap, string typeName)[] actionMaps)
        {
            builder.Append(_Indent).Append($"public static class {_ClassName}\n");
            builder.Append(_Indent).Append("{\n");

            // メンバーは自身を囲むクラスと同名にできない
            var fieldNames = new HashSet<string> { _ClassName };

            foreach (var (_, typeName) in actionMaps)
            {
                var fieldName = ResolveUniqueName(typeName, fieldNames);

                builder.Append(_Indent).Append(_Indent)
                    .Append($"public static readonly {typeName} {fieldName} = new {typeName}();\n");
            }

            builder.Append(_Indent).Append("}\n");
        }

        private static void AppendActionMap(StringBuilder builder, InputActionMap actionMap, string typeName)
        {
            builder.Append(_Indent).Append($"public sealed class {typeName}\n");
            builder.Append(_Indent).Append("{\n");

            // メンバーは自身を囲むクラスと同名にできない
            var fieldNames = new HashSet<string> { typeName };
            var mapIdFieldName = ResolveUniqueName(_MapIdFieldName, fieldNames);

            builder.Append(_Indent).Append(_Indent)
                .Append($"public readonly Guid {mapIdFieldName} = new Guid(\"{actionMap.id}\");\n");

            foreach (var inputAction in actionMap.actions)
            {
                var fieldName = ResolveUniqueName(inputAction.name, fieldNames);

                builder.Append(_Indent).Append(_Indent)
                    .Append($"public readonly Guid {fieldName} = new Guid(\"{inputAction.id}\");\n");
            }

            builder.Append(_Indent).Append("}\n");
        }

        /// <summary>
        /// 識別子へ変換した上で、既出の名前と衝突しないよう採番します
        /// </summary>
        private static string ResolveUniqueName(string name, HashSet<string> usedNames)
        {
            var identifier = ToIdentifier(name);
            var uniqueName = identifier;

            for (var suffix = 2; usedNames.Add(uniqueName) == false; suffix++)
            {
                uniqueName = identifier + suffix;
            }

            return uniqueName;
        }

        /// <summary>
        /// 任意の文字列をC#の識別子へ変換します
        /// </summary>
        private static string ToIdentifier(string name)
        {
            if (string.IsNullOrEmpty(name))
            {
                return "_";
            }

            var builder = new StringBuilder(name.Length);

            foreach (var c in name)
            {
                builder.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
            }

            // 識別子は数字から始められない
            if (char.IsDigit(builder[0]))
            {
                builder.Insert(0, '_');
            }

            var identifier = builder.ToString();

            return _ReservedKeywords.Contains(identifier) ? "@" + identifier : identifier;
        }

        /// <summary>
        /// 内容に変化がある場合のみ書き出し、不要な再コンパイルを避けます
        /// </summary>
        private static bool WriteIfChanged(string code)
        {
            if (File.Exists(_SavePath) && File.ReadAllText(_SavePath) == code)
            {
                return false;
            }

            // フォルダがない場合は生成する
            Directory.CreateDirectory(_ExportFolder);

            // .csファイルの作成
            File.WriteAllText(_SavePath, code, new UTF8Encoding(true));
            AssetDatabase.ImportAsset(_SavePath, ImportAssetOptions.ForceUpdate);

            return true;
        }
    }
}
